package org.astral.findmaimaiultra.been.pixiv.model.pages.photo;

public class Photo {
    private Urls urls;
    private int width;
    private int height;

    // Getters and Setters
    public Urls getUrls() {
        return urls;
    }

    public void setUrls(Urls urls) {
        this.urls = urls;
    }

    public int getWidth() {
        return width;
    }

    public void setWidth(int width) {
        this.width = width;
    }

    public int getHeight() {
        return height;
    }

    public void setHeight(int height) {
        this.height = height;
    }
}
